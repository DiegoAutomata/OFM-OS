export function selectCanonicalExamples(profile: ModelProfile, limit = 2) {
  const profileTokens = profileSearchTokens(profile);
  return canonicalExamples
    .map((example) => ({
      example,
      score: similarityScore(profile, example.input, profileTokens),
    }))
    .sort((left, right) => right.score - left.score)
    .slice(0, limit)
    .map(({ example }) => example);
}

function similarityScore(
  profile: ModelProfile,
  example: ModelProfile,
  profileTokens: Set<string>,
) {
  const exampleTokens = profileSearchTokens(example);
  let score = normalizeIdentityGender(profile.identityGender) ===
    normalizeIdentityGender(example.identityGender)
    ? 12
    : 0;
  for (const token of exampleTokens) {
    if (profileTokens.has(token)) score += 1;
  }
  return score;
}

function profileSearchTokens(profile: ModelProfile) {
  return new Set(
    [
      profile.identityGender,
      profile.primaryBodyType,
      profile.secondaryBodyType,
      profile.styleTags.join(" "),
      profile.realPersonality,
      profile.comfortablePersonalityOnline.join(" "),
      profile.confirmedFetishesOrNiches,
    ]
      .join(" ")
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .match(/[a-z0-9]+/g) ?? [],
  );
}

function normalizeIdentityGender(value: string) {
  const normalized = value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
  if (/\btrans\b/.test(normalized)) return "trans-woman";
  if (/\b(cis|woman|mujer)\b/.test(normalized)) return "cis-woman";
  return normalized.trim();
}

